// Base dates calculated dynamically
const now = new Date();
const addDays = (d: number) => {
  const dt = new Date(now);
  dt.setDate(dt.getDate() + d);
  return dt.toISOString();
};
const subDays = (d: number) => {
  const dt = new Date(now);
  dt.setDate(dt.getDate() - d);
  return dt.toISOString();
};

